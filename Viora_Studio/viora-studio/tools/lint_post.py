def load_terms():
    """Словарь терминов из reference/simple.md: термин -> объяснение одной строкой.

    Таблица в файле имеет вид `| термин | по-человечески | ловит или молчит |`.
    Линтер читает её так же, как читает банк приветствий: правила живут
    в тексте скилла. Строки с пометкой «молчит» в W-JARGON не идут: эти слова
    читатель канала знает и без объяснения.
    """
    rows = read_lines(os.path.join(SKILL, "reference", "simple.md"))
    out = {}
    inside = False
    for row in rows:
        bare = row.strip()
        if bare.startswith("## "):
            inside = "словар" in bare.lower()
            continue
        if not inside or not bare.startswith("|"):
            continue
        cells = [cell.strip() for cell in bare.strip("|").split("|")]
        if len(cells) < 2:
            continue
        term = cells[0].strip("`*_ ").lower()
        plain = cells[1].strip()
        if not term or term in ("термин", "---") or set(term) <= set("-: "):
            continue
        if len(cells) > 2 and cells[2].strip().lower().startswith("молч"):
            continue
        out[term] = plain
    return out


