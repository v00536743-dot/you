# Слова канала, которые в словарь простых объяснений не идут: их читатель знает.
LEXICON_SKIP = {"абуз", "акк", "рега", "робит", "халява", "жир", "годнота"}


def jargon_hits(text, terms):
    """Термины из словаря, которые стоят в тексте без объяснения рядом.

    Объяснением считается «это» или скобка с пояснением в том же абзаце.
    Блок «Простыми словами:» снимает претензию ко всему посту сразу.
    """
    body = nolinks(text)
    low = body.lower()
    if SIMPLE_BLOCK in low:
        return []
    out = []
    for block in re.split(r"\n\s*\n", body):
        chunk = block.lower()
        explained = " это " in chunk or "(" in block
        if explained:
            continue
        for term in terms:
            if term in LEXICON_SKIP:
                continue
            # Дефис входит в границу слова: «npx inspo-mcp install» это имя
            # пакета, а не термин MCP. Сам «mcp-сервер» стоит в словаре строкой.
            if re.search(r"(?<![0-9a-zа-яё-])%s(?![0-9a-zа-яё-])" % re.escape(term), chunk):
                if term not in out:
                    out.append(term)
    return out


