def smiley(text):
    """Скобка-улыбка: закрывающих скобок больше, чем открытых.

    Так «!)))» и «и многое другое))» считаются улыбкой, а пояснение
    в скобках (вот такое) улыбкой не считается.
    """
    plain = nolinks(text)
    return plain.count(")") > plain.count("(")


def soul(text):
    """Счёт маркеров души: сколько в тексте живого человека.

    Семь маркеров, по одному баллу. Ни один не обязателен, но сухой текст
    без двух из них читается как отчёт, даже когда правила соблюдены.
    Возвращает (счёт, максимум, чего не хватает словами).
    """
    body = nolinks(text)
    low = body.lower()
    rows = [row for row in body.split("\n") if row.strip()]
    head = " ".join(rows[:2]).lower()
    tail = " ".join(rows[-2:]).lower() if rows else ""
    marks = [
        ("тёплое обращение к читателям", has_any(low, WARM)),
        # Честная оценка вещи своими словами («проект пока сырой») это тоже
        # мнение автора, просто без слова-маркера впереди.
        ("мнение автора одной строкой", has_any(low, OPINION) or has_any(low, HONEST)),
        ("скобка-улыбка", smiley(text)),
        ("восклицание в первых двух строках", "!" in head),
        ("блок «Простыми словами:»", SIMPLE_BLOCK in low),
        ("драма факта в крючке", has_any(head, CONTRAST) or has_any(low, CONTRAST)),
        ("живая концовка", live_end(text)),
    ]
    live = sum(1 for _, ok in marks if ok)
    missing = [name for name, ok in marks if not ok]
    return live, len(marks), missing


def live_end(text):
    """Концовка зовёт делать: пересылка, действие, где лежит код.

    Смотрим две последние непустые строки тела. Хэштег и футер сюда не входят:
    их вызывающий уже отрезал, а на всякий случай отсекаем и здесь.
    """
    rows = [
        row for row in nolinks(text).split("\n")
        if row.strip() and not row.strip().startswith("#") and not footer_row(row)
    ]
    tail = " ".join(rows[-2:]).lower()
    return has_any(tail, LIVE_END) or has_any(tail, FORWARD)


